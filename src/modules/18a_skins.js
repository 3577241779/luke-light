function skinId() {
  try {
    var k = String((cfg && cfg.skin) || 'ultra');
    return AR6_SKINS[k] ? k : 'ultra';
  } catch (e) { return 'ultra'; }
}

function skinSpec(id) {
  var k = id && AR6_SKINS[id] ? id : skinId();
  return AR6_SKINS[k] || AR6_SKINS.ultra;
}

function sk(key, fallback) {
  var s = skinSpec();
  if (!s || s.id === 'ultra') return fallback;
  var v = s[key];
  return (v !== undefined && v !== null && v !== '') ? v : fallback;
}

function uiSkinBarHTML() {
  if (!SKIN_BAR_OPEN) return '';
  var cur = skinId();
  var h = '<div class="ar6-skinbar" role="group" aria-label="快捷切换皮肤">';
  h += '<span class="ar6-skinbar-lbl">🎨 皮肤</span>';
  for (var i = 0; i < AR6_SKIN_ORDER.length; i++) {
    var id = AR6_SKIN_ORDER[i];
    var sp = AR6_SKINS[id];
    if (!sp) continue;
    var on = (id === cur);
    h += '<button type="button" class="ar6-skinpill' + (on ? ' on' : '') + '" data-ar6="skin:' + esc(id) + '" aria-pressed="' + (on ? 'true' : 'false') + '" title="' + esc(sp.desc || sp.name) + '">' +
      '<i class="ar6-skindot" style="background:' + esc(sp.accent || '#38BDF8') + '"></i>' +
      '<span>' + esc(sp.icon + ' ' + sp.short) + '</span></button>';
  }
  h += '</div>';
  return h;
}

